"""Generate Claude Code skill shims from the canonical, agent-agnostic skills.

Canonical skills live in .codeangel/skills/<name>/SKILL.md (Agent Skills spec; Codex and Cursor read
them natively). Claude Code only discovers .claude/skills/, and committed symlinks break on Windows
(core.symlinks=false), so every canonical skill gets a committed shim .claude/skills/<name>/SKILL.md
that carries Claude-only frontmatter (from `metadata: claude-<field>: <value>`) and points at the source.

  python .codeangel/sync-shims.py           write / update / prune shims
  python .codeangel/sync-shims.py --check   exit 1 if any shim is missing, stale, or orphaned (CI)

Exit codes: 0 in sync, 1 out of sync (--check), 2 invalid canonical skill.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / ".codeangel" / "skills"
TARGET = ROOT / ".claude" / "skills"
MARKER = "<!-- GENERATED by .codeangel/sync-shims.py"
SPEC_KEYS = {"name", "description", "license", "compatibility", "metadata", "allowed-tools"}
NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
BARE_RE = re.compile(r"^(true|false|[a-z][a-z0-9-]*)$")


class SkillError(Exception):
    pass


def rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def unquote(value: str) -> str:
    if len(value) >= 2 and value[0] == value[-1] == '"':
        return json.loads(value)
    if len(value) >= 2 and value[0] == value[-1] == "'":
        return value[1:-1].replace("''", "'")
    return value


def parse_frontmatter(path: Path) -> dict:
    """Parse the flat YAML subset the Agent Skills spec uses (scalars + one-level metadata map)."""
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    if not text.startswith("---\n") or text.count("---\n") < 2:
        raise SkillError(f"{rel(path)}: missing '---' frontmatter")
    data: dict = {}
    parent = None
    for line in text.split("---\n", 2)[1].splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, sep, value = line.strip().partition(":")
        if not sep:
            raise SkillError(f"{rel(path)}: unparseable frontmatter line {line!r}")
        value = unquote(value.strip())
        if line[0] in " \t":
            if parent is None:
                raise SkillError(f"{rel(path)}: indented line outside a map: {line!r}")
            data[parent][key] = value
        elif value == "":
            parent, data[key] = key, {}
        else:
            parent, data[key] = None, value
    return data


def validate(name: str, data: dict, path: Path) -> None:
    where = rel(path)
    unknown = sorted(set(data) - SPEC_KEYS)
    if unknown:
        raise SkillError(f"{where}: non-spec frontmatter {unknown}; put harness fields in metadata")
    if data.get("name") != name:
        raise SkillError(f"{where}: name {data.get('name')!r} must equal its directory {name!r}")
    if len(name) > 64 or not NAME_RE.match(name):
        raise SkillError(f"{where}: name must be 1-64 chars of a-z, 0-9, single hyphens")
    if not 1 <= len(data.get("description", "")) <= 1024:
        raise SkillError(f"{where}: description must be 1-1024 characters")
    if not isinstance(data.get("metadata", {}), dict):
        raise SkillError(f"{where}: metadata must be a map")


def scalar(value: str) -> str:
    return value if BARE_RE.match(value) else json.dumps(value, ensure_ascii=False)


def render(name: str, data: dict) -> str:
    lines = ["---", f"name: {name}", f"description: {scalar(data['description'])}"]
    for key, value in data.get("metadata", {}).items():
        if key.startswith("claude-"):
            lines.append(f"{key[len('claude-') :]}: {scalar(value)}")
    source = f".codeangel/skills/{name}"
    lines += [
        "---",
        "",
        f"{MARKER} from {source}/SKILL.md — do not edit; edit the source,"
        " then run: python .codeangel/sync-shims.py -->",
        "",
        f"Read `{source}/SKILL.md` and follow it exactly. Arguments: $ARGUMENTS",
        f"Its relative paths (`references/`, `scripts/`, `assets/`) resolve inside `{source}/`.",
        "",
    ]
    return "\n".join(lines)


def plan() -> list[tuple[str, Path, str | None]]:
    expected, errors = {}, []
    for skill in sorted(SOURCE.glob("*/SKILL.md")):
        name = skill.parent.name
        try:
            data = parse_frontmatter(skill)
            validate(name, data, skill)
        except SkillError as error:
            errors.append(str(error))
            continue
        expected[name] = render(name, data)
    changes: list[tuple[str, Path, str | None]] = []
    for name, content in expected.items():
        shim = TARGET / name / "SKILL.md"
        current = shim.read_text(encoding="utf-8").replace("\r\n", "\n") if shim.is_file() else None
        if current == content:
            continue
        if current is not None and MARKER not in current:
            errors.append(f"{rel(shim)}: hand-written skill collides with {rel(SOURCE / name)}")
            continue
        changes.append(("write", shim, content))
    for shim in sorted(TARGET.glob("*/SKILL.md")):
        if shim.parent.name not in expected and MARKER in shim.read_text(encoding="utf-8"):
            changes.append(("prune", shim, None))
    if errors:
        raise SkillError("\n".join(errors))
    return changes


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report drift, change nothing")
    args = parser.parse_args()
    try:
        changes = plan()
    except SkillError as error:
        print(f"ERROR:\n{error}")
        return 2
    for action, shim, content in changes:
        print(f"{'would ' if args.check else ''}{action} {rel(shim)}")
        if args.check:
            continue
        if action == "write":
            shim.parent.mkdir(parents=True, exist_ok=True)
            with shim.open("w", encoding="utf-8", newline="\n") as handle:
                handle.write(content)
        else:
            shim.unlink()
            if not any(shim.parent.iterdir()):
                shim.parent.rmdir()
    if args.check and changes:
        print("shims out of sync -> run: python .codeangel/sync-shims.py")
        return 1
    print("shims in sync" if not changes else f"{len(changes)} shim(s) updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
